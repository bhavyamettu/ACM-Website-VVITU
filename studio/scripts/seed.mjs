// One-time migration of the old hard-coded content into Sanity.
//   cd studio && npm run seed      (needs SANITY_AUTH_TOKEN, SANITY_STUDIO_PROJECT_ID in studio/.env)
// Safe to re-run: documents use fixed ids (createOrReplace).
import { readFileSync, existsSync } from 'node:fs';
import { createClient } from '@sanity/client';
import { MEMBERS, BLOGS, EVENTS, TEAM } from './seed-data.js';

if (existsSync('.env')) {
  readFileSync('.env', 'utf8').split('\n').forEach((l) => {
    const m = l.match(/^([A-Z_]+)=(.*)$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim();
  });
}
const { SANITY_STUDIO_PROJECT_ID: projectId, SANITY_STUDIO_DATASET: dataset = 'production', SANITY_AUTH_TOKEN: token } = process.env;
if (!projectId || !token) throw new Error('Set SANITY_STUDIO_PROJECT_ID and SANITY_AUTH_TOKEN in studio/.env');
const client = createClient({ projectId, dataset, token, apiVersion: '2025-01-01', useCdn: false });

const d = new Date();
const a = Math.max(2025, d.getMonth() >= 5 ? d.getFullYear() : d.getFullYear() - 1);
const YEAR = `${a}-${String((a + 1) % 100).padStart(2, '0')}`;
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const MONTHS = { Jan: '01', Feb: '02', Mar: '03', Apr: '04', May: '05', Jun: '06', Jul: '07', Aug: '08', Sep: '09', Oct: '10', Nov: '11', Dec: '12' };

const docs = [];
['SPARDHA', 'AVEGA', 'HOUR OF CODE', 'TECH TALKS', 'VIVA VVIT'].forEach((t, i) => docs.push({ _id: `event-${slug(t)}`, _type: 'event', title: t, visibility: 'public', order: (i + 1) * 10 }));
['ACM', 'ACM-W'].forEach((t, i) => docs.push({ _id: `event-${slug(t)}`, _type: 'event', title: t, visibility: 'private', order: (i + 1) * 10 }));

const teamKey = { acm: 'acm', acmw: 'acmw', heads: 'heads' };
Object.entries(TEAM).forEach(([k, list]) => {
  list.forEach((m, i) => {
    if (m.n === 'Name Surname') return; // placeholders are generated by the site
    docs.push({ _id: `team-${YEAR}-${k}-${i}`, _type: 'teamMember', name: m.n, role: m.r, team: teamKey[k], academicYear: YEAR, order: (i + 1) * 10 });
  });
});

['ACM', 'ACMW'].forEach((k) =>
  MEMBERS[k].forEach((n, i) =>
    docs.push({ _id: `community-${k.toLowerCase()}-${i + 1}`, _type: 'communityMember', name: n, membershipId: `${k}2025${String(i + 1).padStart(3, '0')}`, membershipType: k.toLowerCase(), academicYear: YEAR })
  )
);

const CAT = { 'TECH & TRENDS': 'Tech & Trends', COMMUNITY: 'Community', LEADERSHIP: 'Leadership', EVENTS: 'Events', 'CAMPUS LIFE': 'Campus Life' };
BLOGS.forEach(([cat, date, title, excerpt]) => {
  const [mon, day, year] = date.replace(',', '').split(' ');
  docs.push({
    _id: `blog-${slug(title)}`, _type: 'blogPost', title, category: CAT[cat], date: `${year}-${MONTHS[mon]}-${day.padStart(2, '0')}`, excerpt, author: 'ACM VVITU', published: true,
    body: [{ _type: 'block', _key: 'b1', style: 'normal', markDefs: [], children: [{ _type: 'span', _key: 's1', text: `${excerpt} Full article content will appear here once published.`, marks: [] }] }],
  });
});

const CALCAT = { 'Tech Talk': 'Talk', "Capture '26": 'Contest', 'Web Dev': 'Workshop' };
Object.entries(EVENTS).forEach(([date, [title, , description]]) =>
  docs.push({ _id: `cal-${date}`, _type: 'calendarEvent', title, date, description, category: CALCAT[title] || 'Other' })
);

const tx = client.transaction();
docs.forEach((doc) => tx.createOrReplace(doc));
await tx.commit();
console.log(`Seeded ${docs.length} documents into ${projectId}/${dataset}`);
